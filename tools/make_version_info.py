"""Write build/version_info.txt (Windows version resource for PyInstaller) from the VERSION file.

The exe then carries ProductName / ProductVersion / FileVersion metadata, which code signing
(SignPath) requires to match the project name and the release version.
Run:  python tools/make_version_info.py   (build_exe.bat and the GitHub Actions build do this)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NAME = "PoB Leveling Companion"
EXE = "PoBLevelingCompanion.exe"

version = (ROOT / "VERSION").read_text(encoding="utf-8").strip()
if not re.fullmatch(r"\d+\.\d+\.\d+", version):
    sys.exit(f"VERSION must look like 1.2.3, got {version!r}")
nums = tuple(int(x) for x in version.split(".")) + (0,)

text = f"""# generated by tools/make_version_info.py from VERSION - do not edit
VSVersionInfo(
  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004,
                    fileType=0x1, subtype=0x0, date=(0, 0)),
  kids=[
    StringFileInfo([StringTable('040904B0', [
      StringStruct('ProductName', '{NAME}'),
      StringStruct('FileDescription', '{NAME}'),
      StringStruct('ProductVersion', '{version}'),
      StringStruct('FileVersion', '{version}'),
      StringStruct('InternalName', 'PoBLevelingCompanion'),
      StringStruct('OriginalFilename', '{EXE}'),
      StringStruct('LegalCopyright', 'MIT License - PoB Leveling Companion contributors'),
    ])]),
    VarFileInfo([VarStruct('Translation', [0x0409, 1200])]),
  ],
)
"""
out = ROOT / "build" / "version_info.txt"
out.parent.mkdir(exist_ok=True)
out.write_text(text, encoding="utf-8")
print(f"{out.relative_to(ROOT)}: {NAME} {version}")
